        let currentPlaceholderIndex = 0;
        let currentCharIndex = 0;
        let intervalId = null;

        function updatePlaceholder() {
            if (currentCharIndex === 0) {
                search.placeholder = "";
            }
            const placeholder = placeholderTexts[currentPlaceholderIndex];
            search.placeholder += placeholder.charAt(currentCharIndex);
            currentCharIndex++;
            if (currentCharIndex >= placeholder.length) {
                currentCharIndex = 0;
                currentPlaceholderIndex = (currentPlaceholderIndex + 1) % placeholderTexts.length;
            }
        }

        function startTyping() {
            updatePlaceholder();
        }
        startTyping();
        clearInterval(intervalId);
        intervalId = setInterval(startTyping, 200); 
